export function getHint(
  prompt: Pick<Prompt, "text" | "category"> & { id?: string },
): string {
  const categoryHints = Object.hasOwn(categoryMotions, prompt.category)
    ? categoryMotions[prompt.category]
    : undefined;
  if (categoryHints && Object.hasOwn(categoryHints, prompt.text))
    return categoryHints[prompt.text];
  if (motions[prompt.text]) return motions[prompt.text];
  const split = prompt.text.indexOf("が");
  if (split > 0 && prompt.text.endsWith("している")) {
    const actor = prompt.text.slice(0, split),
      action = prompt.text.slice(split + 1);
    const actorHint =
      motions[actor] ?? "人物や動物の特徴を、姿勢・歩き方・表情で表す。";
    const actionHint =
      actionMotions[action] ??
      "使う道具を持つまねをして、手足の動きを大きく表す。";
    return `まず特徴を出す：${actorHint}\nその特徴を残して：${actionHint}`;
  }
  return "お題の特徴的な形を手や姿勢で表し、それに関わる動きを大きく、ゆっくり繰り返してみよう。";
}
